# 그게 문제인 이유: **예측 목표점은 시간이 갈수록 멀어진다.** 깊이가 초반에
# 과소추정됐다가(errors-in-variables) 관측이 쌓이며 참값 쪽으로 올라오기 때문이다
# (MIN_TIME_SPAN_S 주석의 표 참고). 초반에 여유를 부리면 목표가 멀어졌을 때 따라잡을
# 시간이 없다. 게다가 모터엔 가속 지연이 있어서, 늦게 속도를 내려 하면 제일 급할 때
# 관성과 싸우게 된다.
#
# 그래서 **앞에서 몰아치고 뒤에서 감속**하도록 남은시간을 이 값으로 나눠서 보낸다:
#     보내는 남은시간 = 실제 남은시간 / DRIVE_AGGRESSION
#     -> 피코가 계산하는 속도가 그만큼 빨라진다
#
# 8.0 은 사실상 **"항상 최대속도로 가라"** 다. 피코가 방향별 바퀴 상한
# (`max_body_speed`, 1.22~1.41 m/s)으로 자르므로 물리적으로 못 내는 속도를 요구하는
# 일은 없고, 결과적으로 **목표 코앞까지 전속으로 붙는다.**
#
#   감속이 시작되는 지점 = 남은거리 < v_max * 남은시간 / DRIVE_AGGRESSION
