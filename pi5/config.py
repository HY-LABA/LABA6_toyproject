# ── 초반 가속 공격성 — 2026-09-07 추가 ──────────────────────────────────
# 피코는 `속도 = 남은거리 ÷ 남은시간` 으로 간다. 그래서 시간이 넉넉한 초반에는
# **일부러 느리게** 간다 — 0.3 m 를 0.5 s 안에 가면 되니 0.6 m/s 만 낸다(최대의 43%).
