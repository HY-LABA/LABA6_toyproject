"""전역 설정값. pi5/ 하위 모든 모듈이 참조한다.

**깊이 추정 방식이 바뀌었다 (2026-08-10).** 예전에는 bbox 크기를 클래스별 기준
크기와 비교해 z를 역산했지만, 물체마다 크기를 등록해야 하고 공중에서 회전하면
보이는 크기가 3배까지 흔들려서 포기했다. 지금은 중력을 자로 쓰는 포물선 최소제곱
(trajectory.py)이므로 **물체 크기를 전혀 몰라도 된다.** 그래서:

  · REFERENCE_SIZE_AT_1M 삭제 — 더 이상 필요 없다
  · TARGET_CLASSES 3개 → TARGET_CLASS 1개("trash") — 종류를 구분할 이유가 없어졌다
  · YOLO는 bbox **중심(u,v)** 만 제공하면 된다. 크기 정밀도(σ_w)는 이제 무관하다
"""

from __future__ import annotations

# ─────────────────────────────────────────────────────────────────────────
# 카메라 — Raspberry Pi 8MP Sony IMX219 + M12 렌즈 (LS40136 / B0103)
# ─────────────────────────────────────────────────────────────────────────
# 1640x1232는 IMX219의 2x2 비닝 모드다. 풀해상도(3280x2464)는 15fps밖에 안 나오고,
# 비닝 모드는 40fps까지 나온다. 궤적 피팅은 시간 스팬이 생명이라 fps를 택했다.
CAMERA_RESOLUTION = (1640, 1232)
CAMERA_FPS = 40

# ── 내부 파라미터 (intrinsics) ──────────────────────────────────────────
# ⚠ 아래 네 값은 **반드시 체스보드 캘리브레이션으로 확정할 것.** 틀리면 궤적 추정이
#   통째로 틀어진다. prep/calibrate.py 를 만들어 cv2.calibrateCamera(핀홀) 또는
#   cv2.fisheye.calibrate(어안)로 재고 이 값을 갱신한다.
#
# 지금 값은 센서 기하만으로 계산한 **placeholder**다:
#     f_px = f_mm / 픽셀크기_mm
#     IMX219 픽셀 1.12µm, 2x2 비닝이라 유효 픽셀은 2.24µm
#     → f_px = f_mm / 0.00224
#   렌즈 초점거리를 2.8mm로 가정 → 1250. 스톡 v2 렌즈(3.04mm)라면 1357이다
#   (data_collection/tools/collect.py의 DEFAULT_FX가 그 값이다).
#
# ⚠ LS40136은 M12 교환식 광각 렌즈다. **실제 초점거리와 화각을 제품 스펙에서
#   확인할 것.** 화각이 90°를 넘으면 핀홀 모델이 성립하지 않으니
#   CAMERA_MODEL을 "fisheye"로 바꾸고 왜곡계수를 채워야 한다.
CAMERA_FX = 1250.0  # 정해야함: 캘리브레이션
CAMERA_FY = 1250.0  # 정해야함: 캘리브레이션
CAMERA_CX = CAMERA_RESOLUTION[0] / 2.0  # 정해야함: 캘리브레이션 (중심 가정은 근사)
CAMERA_CY = CAMERA_RESOLUTION[1] / 2.0  # 정해야함: 캘리브레이션

# "pinhole"이면 왜곡계수 4개(k1,k2,p1,p2), "fisheye"면 4개(k1..k4).
# None이면 왜곡 보정을 건너뛴다 — 광각 렌즈에서는 위험하다.
CAMERA_MODEL = "pinhole"  # 정해야함: 렌즈 화각 확인 후 결정
CAMERA_DISTORTION: tuple[float, ...] | None = None  # 정해야함: 캘리브레이션

# ─────────────────────────────────────────────────────────────────────────
# YOLO — 단일 클래스
# ─────────────────────────────────────────────────────────────────────────
YOLO_MODEL_PATH: str | None = None  # 정해야함: 학습 후 .hef 경로
YOLO_CONF_THRESHOLD = 0.5

# 클래스가 하나다. 종류를 구분해도 쓸 데가 없고(크기 기준값이 필요 없어졌으므로),
# 클래스를 늘리면 수집 노동만 배로 늘어난다.
TARGET_CLASS = "trash"

# ─────────────────────────────────────────────────────────────────────────
# 궤적 피팅 (trajectory.py)
# ─────────────────────────────────────────────────────────────────────────
GRAVITY = 9.8

# 카메라 좌표계에서 본 중력 벡터. 카메라가 정확히 위를 보면 광축(+Z)의 반대방향이다.
# 기울여 달았으면 이 벡터만 회전시켜 넣으면 수식은 그대로 성립한다.
GRAVITY_CAM = (0.0, 0.0, -GRAVITY)

# 착지 기준면. 0.0 = **카메라 모듈이 있는 평면**.
# 쓰레기통 입구 높이를 모르므로 카메라 높이를 기준으로 삼는다 — 카메라가 로봇에
# 실려 있으니 "물체가 카메라 높이까지 내려온 순간"이 곧 받는 순간이다.
CATCH_HEIGHT_M = 0.0

# 최소 관측 수. 미지수 6개 / 관측당 식 2개라 수학적으로는 3이면 풀리지만,
# 3이면 정방행렬이라 노이즈를 전혀 못 걸러낸다. 4부터 최소제곱이 작동한다.
MIN_OBSERVATIONS = 4

# ★ 가장 중요한 파라미터. **합성 투척으로 실측해서 정한 값이다.**
#
#   처짐량(⅛·g·T²)만 보고 "0.15초면 충분"하다고 계산했었는데 **틀렸다.** 실제로는
#   관측값 자체(a=u−cx)가 행렬 A에 들어가므로, 픽셀 노이즈가 우변뿐 아니라 계수에도
#   섞인다(errors-in-variables). 그 결과 깊이가 **계통적으로 과소추정**되고, 스팬이
#   길어져야 서서히 참값으로 수렴한다.
#
#   깊이 추정비율(추정/참값), 노이즈 1px, 40fps 기준 — 1.0이 정확:
#       z0      0.30s   0.40s   0.50s   0.60s   0.70s
#       1.5m    0.35    0.75    0.94    0.99    1.00
#       2.5m    0.13    0.35    0.69    0.90    0.97
#       3.5m    0.07    0.16    0.37    0.67    0.86
#
#   → 물체가 **가까울수록 훨씬 빨리 수렴**한다. 카메라 배치를 잡을 때 이걸 기준으로
#     할 것 (멀리서 보는 것보다 가까이서 오래 보는 게 낫다).
#   → 검출 노이즈를 줄이면(0.5px) 필요 스팬이 0.1~0.2초 줄어든다. 모션 블러 억제가
#     그대로 예측 정확도로 돌아온다는 뜻이다.
#
#   여기 0.40s는 **하한선**일 뿐이고, 실제 수렴 판정은 아래 DEPTH_STABILITY_RATIO가
#   한다. 하한을 두는 이유는 그 전에는 계산 자체가 낭비이기 때문.
MIN_TIME_SPAN_S = 0.40

# 조건수 상한. 시간 스팬이 짧거나 궤적이 거의 직선이면 폭발한다.
MAX_CONDITION = 1e9

# 재투영 잔차 상한(px). 포물선으로 설명이 안 되는 궤적(사람 팔, 흔들리는 커튼,
# 검출 오탐)을 걸러내는 **탄도 게이트**다.
#
# ⚠ 단, 잔차는 **깊이 정확도의 지표가 아니다.** 스케일이 틀린 궤적도 화면에는 잘
#   맞게 투영되기 때문이다 — 그게 단안 카메라의 원래 모호성이다. 실측에서 스팬
#   0.5초일 때 잔차가 1.58px로 아주 좋아 보이는데 깊이는 참값의 69%였다.
#   깊이 신뢰도는 DEPTH_STABILITY_RATIO로 따로 판정한다.
MAX_RESIDUAL_PX = 4.0

# ── 깊이 수렴 판정 ──────────────────────────────────────────────────────
# 전체 관측으로 푼 깊이와, 앞쪽 일부만으로 푼 깊이를 비교한다. 깊이는 스팬이 짧을수록
# 작게 나오는 계통 편향이 있으므로, 두 값이 가까워졌다는 건 곧 수렴했다는 뜻이다.
# 노이즈 크기를 미리 몰라도 되는 자기 교정식 판정이라 이 방식을 택했다.
DEPTH_CHECK_FRACTION = 0.7    # 앞쪽 70%만으로 다시 풀어서 비교
#
# 이 값을 조이면 정확해지지만 **예측이 너무 늦게 나온다.** 합성 투척 실측
# (z0=2.5m, 40fps, 150회 중앙값). "남은"은 첫 예측 시점에 착지까지 남은 시간:
#
#   ratio   노이즈    첫예측     남은      첫오차    최종오차   성공률
#    1.15    1.0px    0.80s     0.08s      0.3cm     0.2cm      23%   ← 너무 늦다
#    2.0     0.5px    0.53s     0.36s      3.4cm     0.1cm     100%
#    2.0     1.0px    0.68s     0.21s      2.0cm     0.2cm     100%   ← 채택
#    3.0     1.0px    0.55s     0.33s      9.6cm     0.2cm     100%
#
# 초기 오차가 커도 괜찮은 이유: 깊이 편향이 항상 **과소추정** 방향이라 로봇이
# 목표에 못 미치게 움직인다. 즉 아래에서 위로 수렴하지 절대 오버슈트하지 않는다.
# 덜 간 만큼은 다음 사이클이 이어서 가면 된다. 반대(과대추정)였다면 위험했다.
DEPTH_STABILITY_RATIO = 2.0

# 물리적으로 말이 되는 깊이 범위(m). 이 밖으로 나가면 해가 발산한 것이다.
Z_RANGE_M = (0.15, 6.0)

# 피팅에 쓸 최근 관측 개수 상한.
TRACK_WINDOW = 40

