# ★★ 카메라 이미지 축 → 로봇 body 축 회전각(rad). ★★  ✅ 2026-09-04 실측 완료
#
# `trajectory.py` 가 푸는 X/Y 는 **화면에서 u/v 가 커지는 방향**이다(수식상 확정).
# 반면 오도메트리·역기구학이 쓰는 건 로봇 body 축(+X=우측, +Y=전방=M1)이다.
# 이 둘은 카메라를 로봇에 **몇 도 돌려 붙였느냐**만큼 어긋나 있고, 예전에는 그
# 회전이 코드 어디에도 없어서 착지점을 그냥 오도메트리에 더하고 있었다 —
# 거리는 맞는데 **방향이 틀린** 곳으로 가는 원인이다.
#
# 회전 하나로 충분한 이유(거울 반전이 필요 없는 이유):
#   카메라 좌표계는 (X=이미지 우, Y=이미지 아래, Z=광축)으로 오른손계이고,
#   카메라가 천장을 보므로 Z = 월드 상방이다. 로봇도 (x=우, y=전방, z=상방)으로
#   오른손계다. 세 번째 축(상방)이 같고 둘 다 오른손계이므로 두 좌표계는
#   **수평면 안의 순수 회전** 관계다. 부호 뒤집힘·축 뒤바뀜은 전부 이 각도
#   하나의 특수한 경우로 표현된다:
#
#       0        →  화면 우 = 로봇 우측,   화면 아래 = 로봇 전방
#       pi/2     →  화면 우 = 로봇 전방,   화면 아래 = 로봇 좌측
#       pi       →  화면 우 = 로봇 좌측,   화면 아래 = 로봇 후방   (부호 둘 다 반전)
#       -pi/2    →  화면 우 = 로봇 후방,   화면 아래 = 로봇 우측
#
# 재는 법 (5분, 로봇을 굴릴 필요 없다):
#   1) 로봇을 세워 두고 카메라 위로 물체를 하나 던진다.
#   2) run.log 의 `landing=(x,y)` 를 읽는다 — 이게 **카메라 축** 착지점이다.
#   3) 그 물체가 실제로 로봇 기준 어느 쪽에 떨어졌는지 자로 잰다(로봇 축).
#   4) 두 벡터 사이의 각도가 이 값이다:
#        CAMERA_YAW_RAD = atan2(실측_y, 실측_x) - atan2(로그_y, 로그_x)
#   5) 서너 번 던져서 같은 값이 나오는지 확인할 것. 안 맞으면 카메라가 정확히
#      위를 안 보고 있는 것이다(GRAVITY_CAM 가정이 깨진다).
#
# 적용 지점은 `tracker.cam_to_robot()` / `tracker.robot_to_cam()` 두 곳뿐이다.
#
# ── 실측 결과 (2026-09-09, 몸체 고정 후 재측정) ─────────────────────────
# 카메라를 완성된 몸체에 고정하면서 **180° 돌아갔다.** 그래서 로봇이 정확히 반대
# 방향으로 갔다 (실기 증상: "속도는 빨라졌는데 방향이 틀어졌다").
#
#       방향    픽셀           카메라축    고도각    yaw 후보
#       front  ( 635,  115)    -93.1°     64.6°   -176.9°
#       right  ( 240,  640)    166.0°     64.0°   -166.0°
#       left   (1180,  530)     -0.6°     58.0°   -179.4°
#       back   ( 672, 1060)     88.4°     57.8°   -178.4°
#
#   기울기까지 같이 푼 결과: yaw = -175.6°, 잔차 1.6~2.7°
#   → **180° 로 반올림.** 4.4° 차이는 착지 1m 에서 7.7cm 이고, 조립/클릭 오차를
#     각도에 굳혀 넣느니 직각을 쓰는 게 낫다.
#
# ⚠ 같이 나온 값: 기울기 3.9° (로봇축 +179.2° 방향, 즉 후방으로 기움).
#   착지 오차 약 4cm 에 해당하고 지금 코드는 보정하지 못한다(GRAVITY_CAM 수직 가정).
#
# ── 이전 측정 (2026-09-04, 카메라를 몸체에 얹기만 했을 때) ──────────────
# 그때는 yaw = +2.1°, 기울기 5.2° 였다. 몸체에 고정하면서 무효가 됐다.
# **카메라를 다시 달 때마다 재야 한다** — measure_camera_yaw.py 로 4방향 촬영.
# ── 참고: 당시 측정값 ────────────────────────────────────────────────────
# 천장 조명 아래에서 사람이 로봇 기준 전/우/후/좌에 서서 4장 촬영, 얼굴 픽셀로 풀었다:
