# ★ body frame 정의 — **M1 방향이 +Y(로봇 전방), 그 오른쪽 직각이 +X**.
#   +X 는 M1 과 M2 사이로 나가는 방향이다. 오른손 좌표계라 omega 는 반시계가 +.
#   실제 배치는 M1 이 앞, M1 에서 보아 오른쪽 아래가 M2, 왼쪽 아래가 M3 다:
#
#                    +Y (전방)
#                       M1  90°
#                        |
#          210° M3 ------+------ M2 330°   --> +X (우측)
#
# 장착각 b_i = 로봇 중심에서 바퀴 i 를 본 **위치각**(+X 축에서 반시계). 옴니 바퀴가
#   구르는 방향은 그 접선이라 b_i + 90° 이고, 그래서 역기구학이
#   w_i = -sin(b_i)·vx + cos(b_i)·vy + L·omega 가 된다 (앞 두 항이 접선 단위벡터).
#   w_i > 0 은 로봇을 반시계로 도는 쪽으로 구르는 것.
#
# ✅ 2026-09-07 몸체 완성 후 실물 대조 완료 — 아래 120° 등간격 배치가 맞다.
