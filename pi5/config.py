# ⚠ 예전 값 120은 **가정에서 나온 값이었고 실측과 3~5배 어긋났다.**
#   당시 주석은 "60fps에서 1000 px/s면 프레임당 17px"이라고 적었는데,
#   실기 로그(2026-08-27~28)에서 던진 캔은 **화면상 2800~3800 px/s**로 움직였고
#   프레임레이트도 60이 아니라 **32fps**였다. 결과가 프레임당 107~121px(최대 292px)이다.
#
#   120이면 앞쪽 몇 프레임이 기존 가설에 못 붙고 미아 가설로 흩어져서
#   **트랙이 잘린다.** 실측 리플레이:
#       ASSOC 120 → 관측  9개 / 스팬 0.256s,  4개 / 0.098s
#       ASSOC 200 → 관측 12개 / 스팬 0.351s,  8개 / 0.227s
#       ASSOC 300 → 관측 12개 / 스팬 0.351s,  9개 / 0.289s
#
#   200이면 대부분 회복된다. 더 키워도 이득이 작고, 넓힐수록 오탐이 붙을 여지가 는다.
#   ※ 물체가 더 빠르거나 프레임레이트가 더 낮아지면 다시 키워야 한다.
