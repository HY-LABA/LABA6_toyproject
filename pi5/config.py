from __future__ import annotations

# ─────────────────────────────────────────────────────────────────────────
# 카메라 — Raspberry Pi 8MP Sony IMX219 + M12 렌즈 (LS40136 / B0103)
# ─────────────────────────────────────────────────────────────────────────
# IMX219 센서 모드 (제조사 스펙):
#     3280x2464  full FOV        0.1~15fps
#     1640x1232  full FOV 비닝    ~30fps      ← 채택
#     1920x1080  크롭            ~30fps
#     1280x720   비닝+크롭        ~60fps
#
# 60fps가 탐나지만 1280x720은 **크롭**이라 화각이 좁아진다(수직 55°→35°). 궤적
# 피팅은 프레임 수보다 **관측 시간 스팬**이 지배적이고, 화각이 좁으면 물체가 화면
# 밖으로 빨리 나가서 스팬 자체가 줄어든다. 그래서 full FOV 30fps를 택했다.
# 30fps면 0.6초에 18프레임 — 충분하다.
CAMERA_RESOLUTION = (1640, 1232)
CAMERA_FPS = 30

# ── 내부 파라미터 (intrinsics) ──────────────────────────────────────────
# 제조사 스펙 (Arducam B0103):
#     센서 유효면적 3.674 x 2.760 mm (1/4"), 3280x2464, 픽셀 1.12µm
#     LS40136 렌즈 수평 화각 70°
#
# 여기서 역산:
#     f_mm  = (3.674/2) / tan(35°) = 2.62 mm
#     f_px  = (1640/2)  / tan(35°) = 1171 px      (1640x1232 비닝 기준)
#   같은 값을 픽셀 크기로도 확인: 2.62mm / 2.24µm(2x2 비닝) = 1170. 일치.
#
# 화각: 수평 70° / 수직 55° / 대각 82°. **90° 미만이므로 핀홀 모델이 성립한다** —
# 어안 캘리브레이션이 필요 없다. 다만 70°는 그래도 광각이라 가장자리에 배럴 왜곡이
# 있으므로 왜곡계수는 채우는 게 좋다.
#
# ⚠ 아래 값은 스펙에서 계산한 것이지 **실측이 아니다.** 개체 편차와 렌즈 장착 상태
#   (M12는 나사식이라 초점을 돌려 맞춘다)에 따라 달라지므로 체스보드로 재서 갱신할 것.
#   궤적 추정이 f에 직접 비례하므로 f가 10% 틀리면 깊이도 10% 틀어진다.
CAMERA_FX = 1171.0  # 스펙 계산값 — 캘리브레이션으로 갱신할 것
CAMERA_FY = 1171.0  # 정사각 픽셀이라 fx와 같다고 봐도 된다
CAMERA_CX = CAMERA_RESOLUTION[0] / 2.0  # 캘리브레이션으로 갱신할 것 (중심 가정은 근사)
CAMERA_CY = CAMERA_RESOLUTION[1] / 2.0  # 캘리브레이션으로 갱신할 것

# 화각 82°(대각)이므로 "pinhole"이 맞다. 왜곡계수는 (k1,k2,p1,p2,k3).
# None이면 보정을 건너뛴다 — 중앙부만 쓰면 큰 문제 없지만, 궤적은 화면을 가로지르므로
# 가장자리 왜곡이 잔차에 계통적으로 섞인다. 캘리브레이션 때 같이 뽑을 것.
CAMERA_MODEL = "pinhole"
CAMERA_DISTORTION: tuple[float, ...] | None = None  # 정해야함: 캘리브레이션

# ─────────────────────────────────────────────────────────────────────────
# YOLO — 단일 클래스
# ─────────────────────────────────────────────────────────────────────────
YOLO_MODEL_PATH: str | None = None  # 정해야함: 학습 후 .hef 경로
YOLO_CONF_THRESHOLD = 0.5

# 클래스가 하나다. 종류를 구분해도 쓸 데가 없고(크기 기준값이 필요 없어졌으므로),
# 클래스를 늘리면 수집 노동만 배로 늘어난다.
TARGET_CLASS = "trash"

# ─────────────────────────────────────────────────────────────────────────
# 궤적 피팅 (trajectory.py)
# ─────────────────────────────────────────────────────────────────────────
GRAVITY = 9.8

# 카메라 좌표계에서 본 중력 벡터. 카메라가 정확히 위를 보면 광축(+Z)의 반대방향이다.
# 기울여 달았으면 이 벡터만 회전시켜 넣으면 수식은 그대로 성립한다.
GRAVITY_CAM = (0.0, 0.0, -GRAVITY)

# 착지 기준면. 0.0 = **카메라 모듈이 있는 평면**.
# 쓰레기통 입구 높이를 모르므로 카메라 높이를 기준으로 삼는다 — 카메라가 로봇에
# 실려 있으니 "물체가 카메라 높이까지 내려온 순간"이 곧 받는 순간이다.
CATCH_HEIGHT_M = 0.0

# 최소 관측 수. 미지수 6개 / 관측당 식 2개라 수학적으로는 3이면 풀리지만,
# 3이면 정방행렬이라 노이즈를 전혀 못 걸러낸다. 4부터 최소제곱이 작동한다.
MIN_OBSERVATIONS = 4

# ★ 가장 중요한 파라미터. **합성 투척으로 실측해서 정한 값이다.**
#
#   처짐량(⅛·g·T²)만 보고 "0.15초면 충분"하다고 계산했었는데 **틀렸다.** 실제로는
#   관측값 자체(a=u−cx)가 행렬 A에 들어가므로, 픽셀 노이즈가 우변뿐 아니라 계수에도
#   섞인다(errors-in-variables). 그 결과 깊이가 **계통적으로 과소추정**되고, 스팬이
#   길어져야 서서히 참값으로 수렴한다.
#
#   깊이 추정비율(추정/참값), 노이즈 1px, 40fps 기준 — 1.0이 정확:
#       z0      0.30s   0.40s   0.50s   0.60s   0.70s
#       1.5m    0.35    0.75    0.94    0.99    1.00
#       2.5m    0.13    0.35    0.69    0.90    0.97
#       3.5m    0.07    0.16    0.37    0.67    0.86
#
#   → 물체가 **가까울수록 훨씬 빨리 수렴**한다. 카메라 배치를 잡을 때 이걸 기준으로
#     할 것 (멀리서 보는 것보다 가까이서 오래 보는 게 낫다).
#   → 검출 노이즈를 줄이면(0.5px) 필요 스팬이 0.1~0.2초 줄어든다. 모션 블러 억제가
#     그대로 예측 정확도로 돌아온다는 뜻이다.
#
#   여기 0.40s는 **하한선**일 뿐이고, 실제 수렴 판정은 아래 DEPTH_STABILITY_RATIO가
#   한다. 하한을 두는 이유는 그 전에는 계산 자체가 낭비이기 때문.
MIN_TIME_SPAN_S = 0.40

# 조건수 상한. 시간 스팬이 짧거나 궤적이 거의 직선이면 폭발한다.
MAX_CONDITION = 1e9

# 재투영 잔차 상한(px). 포물선으로 설명이 안 되는 궤적(사람 팔, 흔들리는 커튼,
# 검출 오탐)을 걸러내는 **탄도 게이트**다.
#
# ⚠ 단, 잔차는 **깊이 정확도의 지표가 아니다.** 스케일이 틀린 궤적도 화면에는 잘
#   맞게 투영되기 때문이다 — 그게 단안 카메라의 원래 모호성이다. 실측에서 스팬
#   0.5초일 때 잔차가 1.58px로 아주 좋아 보이는데 깊이는 참값의 69%였다.
#   깊이 신뢰도는 DEPTH_STABILITY_RATIO로 따로 판정한다.
MAX_RESIDUAL_PX = 4.0

# ── 깊이 수렴 판정 ──────────────────────────────────────────────────────
# 전체 관측으로 푼 깊이와, 앞쪽 일부만으로 푼 깊이를 비교한다. 깊이는 스팬이 짧을수록
# 작게 나오는 계통 편향이 있으므로, 두 값이 가까워졌다는 건 곧 수렴했다는 뜻이다.
# 노이즈 크기를 미리 몰라도 되는 자기 교정식 판정이라 이 방식을 택했다.
DEPTH_CHECK_FRACTION = 0.7    # 앞쪽 70%만으로 다시 풀어서 비교
#
# 이 값을 조이면 정확해지지만 **예측이 너무 늦게 나온다.** ratio=1.15로 조였을 때는
# 예측이 착지 0.08초 전에야 나와서 로봇이 움직일 시간이 없었다(성공률 23%).
#
# 실제 카메라 스펙(f=1171px, 1640x1232 @30fps, 화각 70°)으로 합성 투척 검증,
# 150회 중앙값. "이동가능"은 첫 예측이 나온 시점부터 착지까지 남은 시간:
#
#   z0     노이즈   비행    화면체류   첫예측   이동가능   첫오차   최종오차  성공률
#   1.5m   0.5px   0.73s    0.67s    0.40s    0.33s    1.5cm    0.1cm   100%
#   1.5m   1.0px   0.73s    0.67s    0.50s    0.23s    1.4cm    0.2cm   100%
#   2.5m   0.5px   0.88s    0.83s    0.57s    0.32s    2.8cm    0.1cm   100%
#   2.5m   1.0px   0.88s    0.83s    0.63s    0.25s    2.2cm    0.3cm   100%
#   2.5m   2.0px   0.88s    0.83s    0.83s    0.05s    0.7cm    0.6cm    93%  ← 너무 늦다
#   3.0m   2.0px   0.95s    0.90s    0.90s    0.05s    0.9cm    0.8cm    48%
#
# → **검출 노이즈 1px 이하가 목표.** 2px면 예측이 착지 직전에야 나와서 못 움직인다.
#   0.5px면 0.32초를 벌어준다. 모션 블러 억제가 그대로 예측 성능이다.
# → 화각 70°가 비행 전체(0.67~0.90초)를 담아준다. 화각을 좁히면(1280x720 크롭으로
#   60fps를 얻는 선택지) 이 체류시간이 줄어서 오히려 손해다.
#
# 초기 오차가 커도 괜찮은 이유: 깊이 편향이 항상 **과소추정** 방향이라 로봇이
# 목표에 못 미치게 움직인다. 즉 아래에서 위로 수렴하지 절대 오버슈트하지 않는다.
# 덜 간 만큼은 다음 사이클이 이어서 가면 된다. 반대(과대추정)였다면 위험했다.
