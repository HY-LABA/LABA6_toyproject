# 라고 명시할 정도다. 노출을 짧게 가져갈수록 모션 블러가 줄고, 블러가 줄면 검출
# 노이즈가 줄고, 그게 곧 깊이 추정 정확도다 (DEPTH_STABILITY_RATIO 주석의 표 참고).
CAMERA_RESOLUTION = (1456, 1088)
CAMERA_FPS = 60

# ── 내부 파라미터 (intrinsics) ──────────────────────────────────────────
# 센서 유효면적 = 1456 x 3.45µm = 5.023mm,  1088 x 3.45µm = 3.754mm
# 렌즈 초점거리 6mm 에서:
#     f_px  = 6.0mm / 3.45µm = 1739 px
#     수평화각 = 2·atan(5.023/2 / 6) = 45°
#     수직화각 = 2·atan(3.754/2 / 6) = 35°
#     대각화각 = 2·atan(6.27/2 / 6)  = 55°
#
# 렌즈 이름에 "광각"이 붙어 있지만 그건 **HQ 카메라(대각 7.9mm)** 기준이다. 이
# GS 센서는 더 작아서(6.3mm) 같은 6mm 렌즈가 오히려 좁게 나온다. 대각 55°는
# 광각이 아니라 표준에 가깝고, **핀홀 모델이 넉넉히 성립한다** — 어안 캘리브레이션
# 필요 없고, 일반 방사왜곡 계수 (k1,k2,p1,p2,k3)면 충분하다.
#
# ⚠ 아래는 스펙 계산값이지 실측이 아니다. CS 마운트는 백포커스를 나사로 돌려
#   맞추는 구조라 초점을 맞추는 과정에서 실효 초점거리가 달라진다. 체스보드로
#   재서 갱신할 것 — 궤적 추정이 f에 직접 비례하므로 f가 10% 틀리면 깊이도 10%
#   틀어진다.
CAMERA_FX = 1739.0  # 스펙 계산값 — 캘리브레이션으로 갱신할 것
CAMERA_FY = 1739.0  # 정사각 픽셀이라 fx와 같다고 봐도 된다
CAMERA_CX = CAMERA_RESOLUTION[0] / 2.0  # 캘리브레이션으로 갱신할 것 (중심 가정은 근사)
CAMERA_CY = CAMERA_RESOLUTION[1] / 2.0  # 캘리브레이션으로 갱신할 것

